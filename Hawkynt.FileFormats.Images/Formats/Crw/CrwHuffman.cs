  /// <summary>One decoding table, flattened so a fixed number of bits indexes it directly.</summary>
  internal sealed class Table {
    public int Bits;
    public ushort[] Entries = [];
  }

  /// <summary>Builds a table where the longest code's width indexes every entry at once.</summary>
  private static Table _Build(byte[] source) {
    var longest = 16;
    while (longest > 0 && source[longest - 1] == 0)
      --longest;

    var entries = new ushort[1 << longest];
    var at = 16;
    var slot = 0;
    for (var length = 1; length <= longest; ++length)
      for (var i = 0; i < source[length - 1]; ++i) {
        var leaf = source[at];
        ++at;
        for (var j = 0; j < 1 << (longest - length); ++j)
          if (slot < entries.Length)
            entries[slot++] = (ushort)(length << 8 | leaf);
      }

    return new() { Bits = longest, Entries = entries };
  }

  public static (Table First, Table Second) Tables(int table) {
    if ((uint)table > 2)
      table = 2;

    return (_Build(_FirstTree[table]), _Build(_SecondTree[table]));
  }

  /// <summary>A big-endian bit reader that drops the zero Canon stuffs after every 0xFF.</summary>
  internal sealed class BitReader(byte[] data, int at) {
    private uint _buffer;
    private int _available;
    private bool _stopped;

    public int Read(int count) {
      if (count <= 0)
        return 0;

      _Fill(count);
      var value = (int)((_buffer << (32 - _available)) >> (32 - count));
      _available -= count;
      return value;
    }

    public int Read(Table table) {
      _Fill(table.Bits);
      var index = (int)((_buffer << (32 - _available)) >> (32 - table.Bits));
      var entry = table.Entries[index];
      _available -= entry >> 8;
      return entry & 0xFF;
    }

    private void _Fill(int count) {
      while (_available < count) {
        byte next = 0;
        if (!_stopped && at < data.Length) {
          next = data[at];
          ++at;
          if (next == 0xFF) {
            // Canon writes a zero after every 0xFF; anything else there ends the stream.
            var stuffing = at < data.Length ? data[at] : (byte)0;
            ++at;
            if (stuffing != 0) {
              _stopped = true;
              next = 0;
            }
          }
        }

        _buffer = (_buffer << 8) | next;
        _available += 8;
      }
    }
  }
