/// <summary>The named single-byte encodings a simple PDF font can start from: code to glyph name.</summary>
/// <remarks>
/// Copied value for value from pdf.js <c>src/core/encodings.js</c> (Apache-2.0), which is the table
/// of ISO 32000-1 Annex D. Two things in it are worth knowing about before reading a code off it:
/// <list type="bullet">
/// <item>WinAnsiEncoding names <c>bullet</c> at 0x7F, 0x81, 0x8D, 0x8F, 0x90 and 0x9D, <c>space</c> at
/// 0xA0 and <c>hyphen</c> at 0xAD. None of those appear in the body of the Annex D table; they are
/// its footnotes ("all unused codes greater than 40 map to the bullet character", nbspace as space,
/// soft hyphen as hyphen), folded in. Viewers draw those codes that way, so the table does too.</item>
/// <item>PDFDocEncoding is a text-string encoding rather than a font encoding and pdf.js keeps it as a
/// table of code points instead of names (<c>PDFStringTranslateTable</c> in
/// <c>src/core/string_utils.js</c>). The names here are those code points looked up in the Adobe
/// Glyph List, with the Latin-1 half named the way WinAnsiEncoding names it; 0x7F, 0x9F and 0xAD are
/// undefined, as Annex D has them.</item>
/// </list>
/// </remarks>
