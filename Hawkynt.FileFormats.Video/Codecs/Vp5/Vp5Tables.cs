/// flags and the linear maps that turn a transmitted probability into a context-conditioned one.
/// </summary>
/// <remarks>
/// Everything here is interoperability data rather than expression. A stream encoded against these
/// numbers decodes to a different picture against any others, so they are transcribed and not
/// derived, and they were transcribed mechanically — a script parsed the C initialisers and wrote
/// this file — because a table somebody retyped is the defect nothing catches until real files
/// arrive.
/// <para/>
/// The source is FFmpeg's <c>libavcodec/vp56data.c</c> and <c>libavcodec/vp5data.h</c>; see
