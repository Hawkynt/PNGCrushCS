/// <summary>
/// The variable-length code tables and scan arrays of SMPTE 421M, transcribed from the tables the
/// standard prints them in.
/// </summary>
/// <remarks>
/// Each code table is a flat run of codeword-and-length pairs, in the index order the standard numbers
/// them: entry <c>n</c> of a table is at <c>[2n]</c> and <c>[2n + 1]</c>, which is a row of the printed
/// table read straight across. Holding them this way rather than as bit strings keeps a table of a
/// hundred and eighty entries comparable against its page column by column, which is the only check
/// that scales to this many of them.
/// <para/>
/// Two properties are asserted over every code table when it is built, and both are strong enough that
/// a single mistyped number fails them: the codes must be prefix-free, and — for every table but the
/// two Mid Rate ones, which reserve the nine-zero codeword — their Kraft sum must be exactly one. A
/// number read from the wrong column shifts every entry after it and breaks both.
/// <para/>
/// The scan arrays carry one repair each. All three are laid out twenty-four columns wide on a page
/// that fits twenty-three, so positions 23 and 47 fall past the right margin and are missing from the
/// document altogether. Each scan is a permutation of 0 to 63, so which two values are absent is not in
/// doubt; which position each belongs in is fixed by the scan's own geometry, since every neighbourhood
/// there continues an anti-diagonal and only one of the two assignments does. Both are confirmed by
/// decoding, since all three scans are exercised by the frames measured against the reference.
/// </remarks>
