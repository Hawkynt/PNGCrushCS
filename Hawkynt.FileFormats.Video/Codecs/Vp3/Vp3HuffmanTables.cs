/// <summary>
/// The eighty DCT token codebooks VP3 has built in, transcribed from Appendix B.4 of the Theora
/// specification.
/// </summary>
/// <remarks>
/// Theora carries these tables in its setup header; VP3 has no setup header and hard-codes them, so
/// a VP3 decoder has to know all eighty by heart. The appendix that lists them prints one code and
/// one token value per line, sorted by the code read as a binary number, and that is exactly the
/// order and the form used here — <c>"01001110:3"</c> is the line <c>b01001110</c>&#160;&#160;<c>3</c>
/// — so that a table of thirty-two codes can be compared against the page it came from line by line.
/// A single wrong bit anywhere in the two thousand five hundred and sixty entries would show up as a
/// picture that is wrong somewhere subtle, and reading across is the only check that scales.
/// <para/>
/// Two more checks are made when the tables are built rather than left to inspection.
/// <see cref="Vp3VlcTable"/> refuses a set of codes where one is a prefix of another, and refuses a
/// set that does not fill its tree — every one of these codebooks is complete, so that any sequence
/// of bits decodes to some token, and a transcription slip that dropped or lengthened a code would
/// break one or the other. What neither check catches is a code that is unique and complete but
/// attached to the wrong token, which is what comparison against a reference decoder is for.
/// <para/>
/// Which of the eighty a token is read with is chosen per frame and per coefficient position: the
/// frame states a four-bit index for the luma plane and another for the chroma planes, once for the
/// DC coefficient and once for the AC coefficients, and the AC index is then offset by sixteen for
/// each of the four coefficient-position groups of Table 7.42.
/// </remarks>
