internal sealed class H264CabacContexts {
  private readonly H264CabacContext[] _states = new H264CabacContext[436];

  public H264CabacContexts(H264SliceHeader header) {
    var table = header.IsIntra ? _I : header.CabacInitIdc switch {
      0 => _Pb0,
      1 => _Pb1,
      2 => _Pb2,
      _ => throw new InvalidDataException($"cabac_init_idc {header.CabacInitIdc} is outside 0..2."),
    };

    _InitializeRange(table, 0, 276, header.SliceQpY);
    _InitializeRange(table, 276 * 2, 399, 37, header.SliceQpY);
  }

  public ref H264CabacContext this[int contextIndex] {
    get {
      if ((uint)contextIndex >= (uint)this._states.Length)
        throw new InvalidDataException($"CABAC context {contextIndex} is outside the implemented AVC context range.");
      return ref this._states[contextIndex];
    }
  }

  private void _InitializeRange(sbyte[] table, int tableOffset, int contextOffset, int count, int qp) {
    for (var i = 0; i < count; ++i)
      this._states[contextOffset + i] = H264CabacContext.Initialize(
        table[tableOffset + i * 2], table[tableOffset + i * 2 + 1], qp);
  }

  private void _InitializeRange(sbyte[] table, int contextOffset, int count, int qp)
    => this._InitializeRange(table, contextOffset * 2, contextOffset, count, qp);

