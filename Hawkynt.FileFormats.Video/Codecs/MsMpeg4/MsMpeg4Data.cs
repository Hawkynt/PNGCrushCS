/// <summary>
/// The code tables Microsoft's three MPEG-4 variants read, exactly as FFmpeg's
/// <c>libavcodec/msmpeg4data.c</c>, <c>msmpeg4_vc1_data.c</c>, <c>h263data.c</c> and
/// <c>mpeg4data.h</c> hold them.
/// </summary>
/// <remarks>
/// Microsoft published no specification for any of the three, and the tables below appear in no
/// standard: they are the format, and the only authoritative statement of them is the free
/// implementation that reverse-engineered them. So they are copied across value for value rather than
/// derived, which is the rule for every table of constants in this repository — a table somebody
/// worked out for themselves is the defect nothing catches until real files arrive, and here there is
/// no normative text to work it out from in the first place.
/// <para/>
/// See <c>THIRD-PARTY-NOTICE.FFmpeg.txt</c> beside this file for where each array came from and under
/// what licence.
/// <para/>
/// The naming follows what each table is for rather than FFmpeg's own, and every pair of arrays named
/// <c>...Codes</c> and <c>...Lengths</c> is one variable-length code table: entry <c>i</c> is the
/// codeword <c>Codes[i]</c> written in <c>Lengths[i]</c> bits, and <c>i</c> itself is the value it
/// stands for.
/// </remarks>
